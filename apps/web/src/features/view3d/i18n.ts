export type Msg3DKey = keyof typeof MSG3D;

/** Text the scene produced as a key and values (`SceneText`), in one language. */
export function tx(lang: Lang3D, text: { key: string; values: Record<string, string | number> }): string {
  return text.key in MSG3D ? t3d(lang, text.key as Msg3DKey, text.values) : text.key;
}

export function t3d(lang: Lang3D, key: Msg3DKey, values: Record<string, string | number> = {}): string {
  const entry: Entry = MSG3D[key];
  const text = entry[lang] || entry.en;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => (values[k] !== undefined ? String(values[k]) : `{${k}}`));
}
