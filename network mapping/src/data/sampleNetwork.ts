// Helper to generate fiber cores
function generateCores(count: number, usedCount: number, reservedCount = 2, damagedCount = 1) {
  const cores = [];
  for (let i = 1; i <= count; i++) {
    const color = getFiberColor(i);
    const tube = getTubeNumber(i);
    let status: 'Available' | 'In Use' | 'Reserved' | 'Damaged' = 'Available';
    let remarks = 'Free Core (Available for allocation)';
    let connEquip = undefined;
    let connPort = undefined;

    if (i <= usedCount) {
      status = 'In Use';
      remarks = `Allocated to Downstream Path (Core ${i})`;
      connEquip = `FAT-0${((i % 8) + 1).toString().padStart(2, '0')}`;
      connPort = `PORT-${i}`;
    } else if (i <= usedCount + reservedCount) {
      status = 'Reserved';
      remarks = 'Reserved for Enterprise Lease Expansion';
    } else if (i === count - 1 && damagedCount > 0) {
      status = 'Damaged';
      remarks = 'High Attenuation / Macro-bend fault recorded on OTDR';
    }

    cores.push({
      coreNumber: i,
      tubeNumber: tube,
      colorName: color.name,
      colorHex: color.hex,
      status,
      connectedToEquipmentId: connEquip,
      connectedToEquipmentName: connEquip ? `Distribution Terminal ${connEquip}` : undefined,
      connectedPort: connPort,
      remarks,
      attenuationDb: status === 'In Use' ? +(0.22 + (i * 0.01)).toFixed(2) : status === 'Damaged' ? 3.45 : undefined
    });
  }
  return cores;
}

